import { readdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { extname, join } from "node:path";

/**
 * Collect every icon this repo actually renders into one generated module,
 * so the browser never has to ask api.iconify.design for them.
 *
 * <iconify-icon> ships no artwork: each icon's SVG is fetched from Iconify's
 * API the first time it appears, then cached in localStorage. That is a fine
 * default for a prototyping tool and a poor one for this platform — the ops
 * app is used on warehouse phones where the first paint of every screen grew
 * icon-shaped holes that filled in whenever the network got around to it,
 * and the storefront's first impression carried the same flicker.
 *
 * This script greps the source for icon names (the same way a person would),
 * resolves each against the @iconify-json data packages, and writes them as
 * a module the apps register with addCollection() at startup. Roughly 70
 * icons come to ~20 KB — less than a single photograph's placeholder — and
 * they render on the first frame, offline included.
 *
 * The runtime fetch is deliberately left in place as the fallback: an icon
 * added without re-running this script still renders, exactly as before,
 * just a beat later. Run `npm run icons` to fold it into the bundle.
 *
 * Scanned alongside the app source: supabase/migrations, because category
 * icons live in a database column and their names appear here only in the
 * seed SQL.
 */

const ROOTS = ["apps/web/src", "apps/ops/src", "packages", "supabase/migrations", "scripts"];
const EXTS = new Set([".ts", ".tsx", ".mjs", ".sql"]);
const SKIP_DIRS = new Set(["node_modules", ".next", "dist", ".git"]);
const OUT_FILE = "packages/ui/src/icons.generated.ts";

/** `solar:box-linear`, `mdi:instagram` — a set prefix, a colon, a name. */
const ICON_PATTERN = /["'`](?<set>[a-z][a-z0-9-]*):(?<name>[a-z][a-z0-9-]*)["'`]/g;

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (!SKIP_DIRS.has(entry.name)) yield* walk(join(dir, entry.name));
    } else if (EXTS.has(extname(entry.name))) {
      yield join(dir, entry.name);
    }
  }
}

/**
 * An alias is a pointer at another icon plus optional transforms (flip,
 * rotate). Resolving it means taking the parent's artwork and laying the
 * alias's own properties over it — parents can themselves be aliases, hence
 * the recursion.
 */
function resolveIcon(name, data) {
  if (data.icons[name]) return data.icons[name];
  const alias = data.aliases?.[name];
  if (!alias) return null;
  const parent = resolveIcon(alias.parent, data);
  if (!parent) return null;
  const { parent: _parent, ...overrides } = alias;
  return { ...parent, ...overrides };
}

const found = new Map(); // set prefix → Set of icon names
for (const root of ROOTS) {
  for await (const file of walk(root)) {
    // The generated module stores names WITHOUT their prefix, so scanning it
    // (it lives under packages/) can never match its own output.
    const text = await readFile(file, "utf8");
    for (const match of text.matchAll(ICON_PATTERN)) {
      const { set, name } = match.groups;
      if (!found.has(set)) found.set(set, new Set());
      found.get(set).add(name);
    }
  }
}

const require = createRequire(import.meta.url);
const collections = [];
const missing = [];

for (const [set, names] of [...found.entries()].sort()) {
  let data;
  try {
    data = require(`@iconify-json/${set}/icons.json`);
  } catch {
    // A prefix that greps like an icon set but is not one we have data for —
    // "https:" never matches the pattern, but a genuinely new set would land
    // here. Say so rather than silently shipping a bundle without it.
    missing.push(`${set}:* (no @iconify-json/${set} installed — npm i -D it, or ignore if not an icon set)`);
    continue;
  }

  const icons = {};
  for (const name of [...names].sort()) {
    const icon = resolveIcon(name, data);
    if (icon) icons[name] = icon;
    else missing.push(`${set}:${name} (no such icon in the set — typo?)`);
  }

  if (Object.keys(icons).length === 0) continue;
  collections.push({
    prefix: data.prefix,
    icons,
    width: data.width,
    height: data.height,
  });
}

const count = collections.reduce((sum, c) => sum + Object.keys(c.icons).length, 0);

const banner = `/**
 * GENERATED by scripts/bundle-icons.mjs — do not edit by hand.
 *
 * Every icon the apps render, resolved from @iconify-json data so it paints
 * on the first frame instead of arriving from api.iconify.design when the
 * network allows. Both IconifyLoaders register these with addCollection().
 *
 * Added an icon somewhere? It still renders (the runtime fetch remains as
 * the fallback) — run \`npm run icons\` to fold it in here.
 */

type BundledIcon = {
  body: string;
  width?: number;
  height?: number;
  left?: number;
  top?: number;
  hFlip?: boolean;
  vFlip?: boolean;
  rotate?: number;
};

export type IconCollection = {
  prefix: string;
  icons: Record<string, BundledIcon>;
  width?: number;
  height?: number;
};

export const iconCollections: IconCollection[] = `;

await writeFile(OUT_FILE, banner + JSON.stringify(collections, null, 2) + ";\n");

console.log(`${OUT_FILE}: ${count} icons across ${collections.length} sets.`);
if (missing.length > 0) {
  console.warn(`\nNot bundled (will fall back to the network):`);
  for (const line of missing) console.warn(`  - ${line}`);
}
